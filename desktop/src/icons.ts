const cache = new Map<string, string>();

/** SVG-иконка: точки цветом текста (`currentColor`), чтобы тема и прозрачность шли от родителя. */
export function icon(glyph: Glyph, size = 16): string {
  const key = `${glyph}:${size}`;
  const hit = cache.get(key);
  if (hit) return hit;
  const circles: string[] = [];
  rows[glyph].forEach((row, y) => {
    [...row].forEach((c, x) => {
      if (c === "#") circles.push(`<circle cx="${x + 0.5}" cy="${y + 2.5}" r="0.5"/>`);
    });
  });
  const svg = `<svg class="dot" width="${size}" height="${size}" viewBox="0 0 16 16" fill="currentColor" aria-hidden="true">${circles.join("")}</svg>`;
  cache.set(key, svg);
  return svg;
}
