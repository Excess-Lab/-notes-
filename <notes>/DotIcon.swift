struct DotIcon: View {
    let glyph: DotGlyph
    var size: CGFloat = 16
    var color: Color = Theme.ink

    var body: some View {
        Canvas { context, canvas in
            // Сетка 16 точек в ширину, 12 в высоту, по центру квадрата — как в компоненте 16×16.
            let dot = canvas.width / 16
            let top = (canvas.height - dot * 12) / 2
            for (y, row) in glyph.rows.enumerated() {
                for (x, char) in row.enumerated() where char == "#" {
                    let rect = CGRect(x: CGFloat(x) * dot, y: top + CGFloat(y) * dot, width: dot, height: dot)
                    context.fill(Path(ellipseIn: rect), with: .color(color))
                }
            }
        }
        .frame(width: size, height: size)
    }
}
